package com.kks.bharatkirana.ui.theme

import androidx.compose.ui.unit.dp

// Spacing scale. Every padding / margin / arrangement.spacedBy(...) should
// pick one of these instead of a raw dp literal. Keeps section rhythm even
// across screens.
object AppSpacing {
  val Xs = 4.dp
  val Sm = 8.dp
  val Md = 12.dp
  val Lg = 16.dp
  val Xl = 24.dp
  val Xxl = 32.dp
  val Xxxl = 48.dp
}
